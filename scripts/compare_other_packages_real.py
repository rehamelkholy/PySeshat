"""
Cross-check of PySeshat against RadVel, PyAstronomy and orbitize! on REAL Capella data.

Replaces, for the paper (Sect. 3.3), scripts/compare_other_packages.py, which used the
synthetic Capella benchmark (data generated by PySeshat itself from Torres et al. 2015).
Data: the same real data as the Capella case study (scripts/capella_real_data.py):
  RVs        CfA velocities of A and B (Torres et al. 2009, table1; 162 epochs each)
  astrometry subset "B" of capella_real_data.SUBSETS (interferometric + speckle/imaging).
Reference: PySeshat's combined visual+RV fit of these data (circular orbit, e = omega = 0
fixed as in Torres et al. 2009; default dataset weighting), recomputed here.

1. RadVel (Fulton et al. 2018): independent maximum-likelihood RV fit of each component
   separately (circular orbit; free P, tc, K, gamma, jitter; P bounded to +-15 % of the
   Torres et al. 2009 period; small multi-start in tc), uncertainties from RadVel's own MCMC.
   Note: RadVel uses the RVs only, PySeshat the RVs and the astrometry, so differences are
   expressed in the combined sigma of both fits.
2. PyAstronomy (Czesla et al. 2019): independent Kepler-equation solver
   (pyasl.MarkleyKESolver) + RV formula vs PySeshat's compute_rv_orbit at the CfA epochs,
   using the fitted P, T0, K1, V0 and e = 0, 0.3, 0.6, 0.9 (a physics check, not a fit;
   e > 0 because the circular case does not exercise the Kepler solver).
3. orbitize! (Blunt et al. 2020): independent fit of the relative astrometry only
   (RA/Dec offsets, MCMC). Parallax: Hipparcos (van Leeuwen 2007) 76.20 +- 0.46 mas, as
   quoted by Torres et al. (2009); total-mass prior N(5, 2) Msun (deliberately broad).
   A bounded OFTI attempt is reported first. The MCMC walkers start in a small ball around
   the published elements of Torres et al. (2009), not around PySeshat's solution.

Needs: radvel, PyAstronomy, orbitize (pip install radvel PyAstronomy orbitize).
Writes validation/results/package_comparison_capella_real.json.
Run: python scripts/compare_other_packages_real.py   (the orbitize! MCMC takes ~10-20 min)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
for p in (ROOT / "src", ROOT / "scripts"):
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

import capella_real_data as cp  # noqa: E402
from pyseshat.analysis.masses import compute_component_masses, compute_total_mass  # noqa: E402
from pyseshat.inference.optimizer import fit_visual_orbit  # noqa: E402
from pyseshat.orbit.orbital_elements import OrbitalElements  # noqa: E402
from pyseshat.orbit.rv_model import compute_rv_orbit  # noqa: E402

OUT = ROOT / "validation" / "results" / "package_comparison_capella_real.json"
PLX_HIP = (76.20, 0.46)          # mas, van Leeuwen (2007) as quoted by Torres et al. (2009)
P_TORRES_YR = cp.PUBLISHED["P"][0]
RESULT = {"data": "Capella real: CfA RVs (Torres+2009 table1) + astrometry subset B",
          "parallax_mas": PLX_HIP}


def pct(a, b):
    return (a - b) / b * 100.0


def pyseshat_reference():
    t, X, Y, sx, sy = cp.astrometry(**cp.SUBSETS["B"])
    rv = cp.rv_cfa()
    f = fit_visual_orbit(cp.start(), t, X, Y, sx, sy, rv_data=rv, weighting="dataset")
    el = f.elements
    vals = dict(zip(el.fitted_parameter_names(), el.fitted_parameters()))
    vals.update(e=el.e, omega=el.omega)
    sig = {k: float(v) for k, v in f.uncertainties.items()}
    ref = {"values": {k: float(v) for k, v in vals.items()}, "sigma": sig,
           "n_astrometry_epochs": int(len(t)), "n_rv_epochs": int((rv[:, 3] == 0).sum()),
           "error_scales": {k: float(v) for k, v in f.metadata["error_scales"].items()}}
    RESULT["pyseshat"] = ref
    print(f"PySeshat reference fit: {len(t)} astrometric epochs, {ref['n_rv_epochs']} RV epochs per star")
    for k in ("P", "T0", "a", "i", "Omega", "K1", "K2", "V0"):
        print(f"   {k:6s} {vals[k]:14.7f} +- {sig[k]:.7f}")
    return ref, t, X, Y, sx, sy, rv


# ---------------------------------------------------------------- 1. RadVel
def _radvel_fit(t, v, e):
    import radvel
    best = None
    for tc0 in P_TORRES_YR * np.arange(8) / 8.0 + np.median(t):
        params = radvel.Parameters(1, basis="per tc secosw sesinw k")
        params["per1"] = radvel.Parameter(value=P_TORRES_YR, vary=True)
        params["tc1"] = radvel.Parameter(value=tc0, vary=True)
        params["secosw1"] = radvel.Parameter(value=0.0, vary=False)   # circular (as Torres+2009)
        params["sesinw1"] = radvel.Parameter(value=0.0, vary=False)
        params["k1"] = radvel.Parameter(value=26.0, vary=True)
        params["dvdt"] = radvel.Parameter(value=0.0, vary=False)
        params["curv"] = radvel.Parameter(value=0.0, vary=False)
        mod = radvel.RVModel(params, time_base=np.median(t))
        like = radvel.likelihood.RVLikelihood(mod, t, v, e, suffix="_cfa")
        like.params["gamma_cfa"] = radvel.Parameter(value=float(np.median(v)), vary=True)
        like.params["jit_cfa"] = radvel.Parameter(value=0.1, vary=True)
        post = radvel.posterior.Posterior(like)
        post.priors.append(radvel.prior.HardBounds("per1", 0.85 * P_TORRES_YR, 1.15 * P_TORRES_YR))
        post.priors.append(radvel.prior.HardBounds("k1", 0.0, 200.0))
        post.priors.append(radvel.prior.HardBounds("jit_cfa", 0.0, 5.0))
        res = radvel.fitting.maxlike_fitting(post, verbose=False)
        lp = float(res.logprob())
        if best is None or lp > best[0]:
            best = (lp, res)
    res = best[1]
    out = {"P_yr": float(res.params["per1"].value), "K": float(res.params["k1"].value),
           "gamma": float(res.params["gamma_cfa"].value), "jitter": float(res.params["jit_cfa"].value)}
    # uncertainties: RadVel's own MCMC around the maximum-likelihood solution
    np.random.seed(1)
    ch = radvel.mcmc(res, nwalkers=40, nrun=3000, ensembles=2, headless=True)
    for key, col in (("P_yr", "per1"), ("K", "k1"), ("gamma", "gamma_cfa")):
        lo, hi = np.percentile(ch[col], [16, 84])
        out[f"sigma_{key}"] = float((hi - lo) / 2.0)
    return out


def run_radvel(ref, rv):
    import radvel
    out = {"version": radvel.__version__}
    pv, ps = ref["values"], ref["sigma"]
    print("\n1. RadVel (circular, each component separately) vs PySeshat combined fit")
    print(f"{'':10s}{'PySeshat':>16s}{'RadVel':>16s}{'':>12s}{'% diff':>10s}{'d/sig':>9s}  (d/sig: combined sigma)")
    for comp, kname in ((0, "K1"), (1, "K2")):
        m = rv[:, 3] == comp
        r = _radvel_fit(rv[m, 0], rv[m, 1], rv[m, 2])
        out[f"component_{comp + 1}"] = r
        for name, rvv, pkey in (("P (d)", r["P_yr"], "P"), (kname, r["K"], kname), ("gamma", r["gamma"], "V0")):
            a, b = rvv, pv[pkey]
            sc = 365.25 if pkey == "P" else 1.0
            sr = r["sigma_" + {"P": "P_yr", "V0": "gamma"}.get(pkey, "K")]
            d = (a - b) / np.hypot(ps[pkey], sr)
            out[f"component_{comp + 1}"][f"pct_diff_{pkey}"] = pct(a, b)
            out[f"component_{comp + 1}"][f"diff_in_combined_sigma_{pkey}"] = d
            print(f"{name:10s}{b * sc:16.5f}{a * sc:16.5f} +-{sr * sc:9.5f}{pct(a, b):+10.4f}{d:+9.2f}   (star {comp + 1})")
        print(f"{'jitter':10s}{'':16s}{r['jitter']:16.4f}")
    RESULT["radvel"] = out


# ---------------------------------------------------------------- 2. PyAstronomy
def run_pyastronomy(ref, rv):
    from PyAstronomy import pyasl
    import PyAstronomy
    pv = ref["values"]
    t = np.sort(rv[rv[:, 3] == 0, 0])
    ks = pyasl.MarkleyKESolver()
    out = {"version": PyAstronomy.__version__, "n_epochs": int(len(t)), "by_e": {}}
    print("\n2. PyAstronomy Kepler solver + RV formula vs PySeshat compute_rv_orbit (CfA epochs)")
    for e in (0.0, 0.3, 0.6, 0.9):
        omega = 30.0
        el = OrbitalElements(P=pv["P"], T0=pv["T0"], e=e, a=pv["a"], Omega=pv["Omega"],
                             omega=omega, i=pv["i"], K1=pv["K1"], K2=pv["K2"], V0=pv["V0"])
        ps = compute_rv_orbit(t, el, component=0)
        M = np.mod(2 * np.pi * (t - el.T0) / el.P, 2 * np.pi)
        E = np.array([ks.getE(m, e) for m in M])
        nu = 2 * np.arctan2(np.sqrt(1 + e) * np.sin(E / 2), np.sqrt(1 - e) * np.cos(E / 2))
        w = np.deg2rad(omega)
        pa = el.K1 * (np.cos(nu + w) + e * np.cos(w)) + el.V0
        d = ps - pa
        out["by_e"][str(e)] = {"max_abs_kms": float(np.max(np.abs(d))), "rms_kms": float(np.sqrt(np.mean(d ** 2)))}
        print(f"   e = {e:.1f}: max |diff| = {np.max(np.abs(d)):.2e} km/s, rms = {np.sqrt(np.mean(d ** 2)):.2e} km/s")
    RESULT["pyastronomy"] = out


# ---------------------------------------------------------------- 3. orbitize!
def _table(t, X, Y, sx, sy):
    from astropy.table import Table
    n = len(t)
    mjd = (np.asarray(t) - 2000.0) * 365.25 + 51544.5
    return Table({"epoch": mjd, "object": np.ones(n, dtype=int),
                  "quant1": np.asarray(Y) * 1000.0, "quant1_err": np.asarray(sy) * 1000.0,   # RA offset (east)
                  "quant2": np.asarray(X) * 1000.0, "quant2_err": np.asarray(sx) * 1000.0,   # Dec offset (north)
                  "quant12_corr": np.full(n, np.nan), "quant_type": np.array(["radec"] * n),
                  "instrument": np.array(["defrd"] * n)})


def run_orbitize(ref, t, X, Y, sx, sy):
    import orbitize
    import orbitize.priors as opriors
    import orbitize.sampler as osampler
    import orbitize.system as osystem
    pv = ref["values"]
    out = {"version": orbitize.__version__, "n_epochs": int(len(t)),
           "mass_prior_Msun": [5.0, 2.0], "period_bounds_yr": [0.85 * P_TORRES_YR, 1.15 * P_TORRES_YR]}
    print(f"\n3. orbitize! {orbitize.__version__}: relative astrometry only, {len(t)} epochs")
    system = osystem.System(1, _table(t, X, Y, sx, sy), 5.0, PLX_HIP[0], mass_err=2.0,
                            plx_err=PLX_HIP[1], fitting_basis="Period")
    ip = system.labels.index("per1")
    system.sys_priors[ip] = opriors.UniformPrior(0.85 * P_TORRES_YR, 1.15 * P_TORRES_YR)
    np.random.seed(42)
    ofti = osampler.OFTI(system)
    acc = 0
    for _ in range(20):
        s = ofti.prepare_samples(10000)
        a_, _l = ofti.reject(s)
        acc += len(a_)
    out["ofti_accepted"], out["ofti_proposed"] = int(acc), 200000
    print(f"   OFTI: {acc}/200000 proposals accepted")
    # MCMC started from the published solution of Torres et al. (2009) (not from PySeshat):
    # with 119 epochs over ~100 periods the posterior is too narrow to be found from the prior
    # (a first run initialised from the prior did not converge: e = 0.08, i and Omega off by 5-6 deg).
    # The published elements are mapped onto orbitize!'s (aop, tau) convention by scanning tau
    # with orbitize!'s own forward model (circular orbit: aop is arbitrary, tau follows it).
    import orbitize.kepler as kep
    Pp, T0p = cp.PUBLISHED["P"][0], cp.PUBLISHED["T0"][0]
    ap, ip_, Op = cp.PUBLISHED["a"][0], cp.PUBLISHED["i"][0], cp.PUBLISHED["Omega"][0]
    plx0 = PLX_HIP[0]
    sma0 = ap * 1000.0 / plx0
    mjd = (np.asarray(t) - 2000.0) * 365.25 + 51544.5

    def chi2(tau, aop=0.0):
        ra, dec, _ = kep.calc_orbit(mjd, sma0, 1e-4, np.radians(ip_), np.radians(aop), np.radians(Op),
                                    tau, plx0, sma0 ** 3 / Pp ** 2, tau_ref_epoch=system.tau_ref_epoch)
        return float(np.sum(((ra - np.asarray(Y) * 1e3) / (np.asarray(sy) * 1e3)) ** 2
                            + ((dec - np.asarray(X) * 1e3) / (np.asarray(sx) * 1e3)) ** 2))
    grid = np.linspace(0.0, 1.0, 20001)
    tau0 = grid[np.argmin([chi2(x) for x in grid])]
    fine = np.linspace(tau0 - 1e-4, tau0 + 1e-4, 401)
    tau0 = float(fine[np.argmin([chi2(x) for x in fine])])
    out["init"] = {"source": "Torres et al. 2009 Table 9", "tau_at_aop0": tau0, "chi2_at_init": chi2(tau0),
                   "n_residuals": int(2 * len(t))}
    print(f"   init from Torres+2009 elements: chi2 = {chi2(tau0):.1f} for {2 * len(t)} residuals")
    ntemps, nwalk, nsteps, nburn = 4, 50, 2000, 500
    mcmc = osampler.MCMC(system, num_temps=ntemps, num_walkers=nwalk, num_threads=1)
    rng = np.random.default_rng(7)
    shape = (ntemps, nwalk)
    aop = rng.uniform(0.0, 360.0, shape)
    plx_s = rng.normal(plx0, 0.05, shape)
    per_s = rng.normal(Pp, 2e-7, shape)
    pos = {"per1": per_s, "ecc1": rng.uniform(0.0, 0.005, shape),
           "inc1": np.radians(rng.normal(ip_, 0.02, shape)), "aop1": np.radians(aop),
           "pan1": np.radians(rng.normal(Op, 0.02, shape)), "tau1": (tau0 + aop / 360.0 + rng.normal(0, 2e-5, shape)) % 1.0,
           "plx": plx_s, "mtot": (ap * 1000.0 / plx_s) ** 3 / per_s ** 2}
    mcmc.curr_pos = np.dstack([pos[k] for k in system.labels])
    out["mcmc"] = {"num_temps": ntemps, "num_walkers": nwalk, "steps": nsteps, "burn_steps": nburn}
    mcmc.run_sampler(total_orbits=nwalk * nsteps, burn_steps=nburn, thin=1)
    post = mcmc.results.post
    # convergence check: medians of the first and second half of the post-burn samples
    halves = np.array_split(post.reshape(nwalk, -1, post.shape[1]) if post.shape[0] == nwalk * nsteps else post[None], 2, axis=1)
    out["half_split_medians"] = {lab: [float(np.median(h[..., j])) for h in halves] for j, lab in enumerate(system.labels)}
    lab = system.labels
    std = np.array([system.basis.to_standard_basis(r.copy()) for r in post])
    per = post[:, lab.index("per1")]
    sma_au = std[:, lab.index("per1")]          # to_standard_basis puts sma in the per1 slot
    plx = post[:, lab.index("plx")]
    a_mas = sma_au * plx
    inc = np.degrees(post[:, lab.index("inc1")])
    pan = np.degrees(post[:, lab.index("pan1")]) % 360.0
    ecc = post[:, lab.index("ecc1")]
    mtot = post[:, lab.index("mtot")]

    def summ(x):
        return [float(np.percentile(x, 16)), float(np.median(x)), float(np.percentile(x, 84))]
    post_s = {"P_yr": summ(per), "a_arcsec": summ(a_mas / 1000.0), "i_deg": summ(inc),
              "Omega_deg": summ(pan), "e": summ(ecc), "mtot_Msun": summ(mtot)}
    out["posterior_16_50_84"] = post_s
    # node branch: compare Omega modulo 180 deg (no RV in orbitize!)
    om = post_s["Omega_deg"][1]
    om_branch = om if abs(((om - pv["Omega"] + 180) % 360) - 180) < 90 else (om + 180.0) % 360.0
    half = {k: (v[2] - v[0]) / 2.0 for k, v in post_s.items()}
    comp = {"P": (post_s["P_yr"][1], pv["P"], half["P_yr"]), "a": (post_s["a_arcsec"][1], pv["a"], half["a_arcsec"]),
            "i": (post_s["i_deg"][1], pv["i"], half["i_deg"]), "Omega": (om_branch, pv["Omega"], half["Omega_deg"])}
    out["comparison"] = {}
    print(f"{'':8s}{'PySeshat':>14s}{'orbitize!':>14s}{'':>12s}{'% diff':>10s}{'d/sig':>9s}  (d/sig: combined sigma)")
    for k, (o, p, so) in comp.items():
        d = (o - p) / np.hypot(ref["sigma"][k], so)
        out["comparison"][k] = {"orbitize_median": o, "orbitize_sigma": so, "pyseshat": p,
                                "pyseshat_sigma": ref["sigma"][k], "pct_diff": pct(o, p), "diff_in_combined_sigma": d}
        print(f"{k:8s}{p:14.6f}{o:14.6f} +-{so:9.6f}{pct(o, p):+10.4f}{d:+9.2f}")
    hs = out["half_split_medians"]
    print("   convergence (medians of 1st/2nd half): " + ", ".join(f"{k} {v[0]:.6g}/{v[1]:.6g}" for k, v in hs.items()))
    out["Omega_raw_median_deg"] = om
    sb2 = compute_component_masses(pv["P"], 0.0, pv["i"], pv["K1"], pv["K2"])
    dyn = compute_total_mass(pv["P"], pv["a"], PLX_HIP[0])
    mt = post_s["mtot_Msun"][1]
    out["mass"] = {"orbitize_mtot_median": mt, "pyseshat_dynamical_same_plx": float(dyn),
                   "pyseshat_sb2_sum": float(sb2["M_total"]),
                   "pct_vs_dynamical": pct(mt, dyn), "pct_vs_sb2": pct(mt, sb2["M_total"])}
    print(f"   mtot: orbitize! {mt:.4f} (16-84: {post_s['mtot_Msun'][0]:.4f}-{post_s['mtot_Msun'][2]:.4f}) | "
          f"PySeshat a^3/P^2 (same parallax) {dyn:.4f} ({pct(mt, dyn):+.2f}%) | "
          f"PySeshat SB2 M1+M2 {sb2['M_total']:.4f} ({pct(mt, sb2['M_total']):+.2f}%)")
    print(f"   e (orbitize!, free): median {post_s['e'][1]:.4f}, 16-84 % {post_s['e'][0]:.4f}-{post_s['e'][2]:.4f}")
    RESULT["orbitize"] = out


if __name__ == "__main__":
    ref, t, X, Y, sx, sy, rv = pyseshat_reference()
    run_radvel(ref, rv)
    run_pyastronomy(ref, rv)
    OUT.write_text(json.dumps(RESULT, indent=1))       # save before the long MCMC
    run_orbitize(ref, t, X, Y, sx, sy)
    OUT.write_text(json.dumps(RESULT, indent=1))
    print(f"\nwrote {OUT}")
