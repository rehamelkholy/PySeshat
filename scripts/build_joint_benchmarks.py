ASSUMED_RV_SIGMA_KMS = 0.1
ASSUMED_PHOTOMETRIC_SIGMA_MAG = 0.03


def _write_inp(path, object_name, ra, dec, elements, visual_rows, rv_rows):

    lines = [
        f"Object:  {object_name}",
        f"RA:      {ra}",
        f"Dec:    {dec}",
        f"P        {elements['P']:.6f}",
        f"T        {elements['T0']:.4f}",
        f"e       {elements['e']:.5f}",
        f"a       {elements['a']:.6f}",
        f"W        {elements['Omega']:.3f}",
        f"w        {elements['omega']:.3f}",
        f"i        {elements['i']:.3f}",
    ]

    if elements["K1"] != 0.0 or elements["K2"] != 0.0:
        lines += [
            f"K1       {elements['K1']:.4f}",
            f"K2       {elements['K2']:.4f}",
            f"V0       {elements['V0']:.4f}",
        ]

    lines.append(
        "C Synthetic observations generated from the published "
        "orbital solution -- see scripts/build_joint_benchmarks.py "
        "module docstring for the full provenance statement."
    )

    for t, theta, rho, sigma in visual_rows:
        lines.append(f"  {t:.4f}  {theta:.3f}  {rho:.5f} {sigma:.5f} I1   1.0   2  synth")

    for t, rv, sigma, tag in rv_rows:
        lines.append(f"  {t:.4f}  {rv:.4f} {sigma:.4f} {tag}")

    path.write_text("\n".join(lines) + "\n")


def _generate_orbit_observations(elements_dict, epochs, has_rv):

    elements = OrbitalElements(**{
        k: v for k, v in elements_dict.items()
    })

    orbit = compute_visual_orbit(np.asarray(epochs), elements)

    theta_true = orbit["theta"]
    rho_true = orbit["rho"]

    sigma = ASSUMED_ASTROMETRIC_SIGMA_ARCSEC

    # Perturb in Cartesian space (uniform sigma in X/Y) then
    # convert back to theta/rho, avoiding a distorted-in-angle
    # noise model at small rho.
    X = rho_true * np.cos(np.deg2rad(theta_true)) + RNG.normal(0, sigma, len(epochs))
    Y = rho_true * np.sin(np.deg2rad(theta_true)) + RNG.normal(0, sigma, len(epochs))

    rho_obs = np.sqrt(X**2 + Y**2)
    theta_obs = np.mod(np.rad2deg(np.arctan2(Y, X)), 360.0)

    visual_rows = [
        (t, th, rh, sigma)
        for t, th, rh in zip(epochs, theta_obs, rho_obs)
    ]

    rv_rows = []

    if has_rv:

        rv1_true = compute_rv_orbit(np.asarray(epochs), elements, component=0)
        rv2_true = compute_rv_orbit(np.asarray(epochs), elements, component=1)

        for t, rv in zip(epochs, rv1_true):
            rv_rows.append((
                t, rv + RNG.normal(0, ASSUMED_RV_SIGMA_KMS), ASSUMED_RV_SIGMA_KMS, "Va"
            ))

        for t, rv in zip(epochs, rv2_true):
            rv_rows.append((
                t, rv + RNG.normal(0, ASSUMED_RV_SIGMA_KMS), ASSUMED_RV_SIGMA_KMS, "Vb"
            ))

    return visual_rows, rv_rows


def _generate_photometry(photometric_dict, distance_pc):

    # The atmosphere grid loaded here also sets the optimizer's
    # temperature BOUNDS (build_parameter_bounds() uses
    # min/max(atmosphere_grid.temperatures) -- see
    # src/pyseshat/inference/photometric_optimizer.py), and the
    # optimizer's *initial guess* is deliberately offset from the
    # literature temperature (+/-3-5%, see build_capella() /
    # build_alpha_cen_ab()) so this is a genuine parameter-recovery
    # test, not an already-at-the-answer one. So the bracket must
    # cover not just the literature temperature itself but also
    # that offset initial guess -- one extra 250K step of margin on
    # each side is enough for a +/-5% offset at these temperatures.
    atmosphere_files = sorted({
        f"ckp00/ckp00_{int(step)}.fits"
        for t in (
            photometric_dict["primary_temperature"],
            photometric_dict["secondary_temperature"],
        )
        for step in (
            250.0 * (t // 250.0) - 250.0,
            250.0 * (t // 250.0),
            250.0 * (t // 250.0) + 250.0,
            250.0 * (t // 250.0) + 500.0,
        )
    })

    grid = load_ck04_grid([
        VALIDATION_DIR / "atmosphere_models" / f
        for f in atmosphere_files
    ])

    passbands = {
        name: load_passband(
            filename=VALIDATION_DIR / "photometry" / "passbands" / fname,
            name=name,
        )
        for name, fname in _PASSBAND_FILES.items()
    }

    synthetic = synthetic_binary_magnitudes(
        atmosphere_grid=grid,
        passbands=passbands,
        zero_points=_ZERO_POINTS,
        primary_temperature=photometric_dict["primary_temperature"],
        secondary_temperature=photometric_dict["secondary_temperature"],
        primary_logg=photometric_dict["primary_logg"],
        secondary_logg=photometric_dict["secondary_logg"],
        # The full 608-file CK04 grid (all 8 metallicity slices,
        # see validation/atmosphere_models/)
        # is available in this project, so metallicity here is a
        # deliberate choice, not a data-availability fallback: 0.0
        # is used because both Capella's and alpha Cen AB's
        # photometric "measurements" are SYNTHETIC, generated by
        # THIS SAME forward-model call, so fitting at 0.0 keeps the
        # benchmark internally self-consistent (recovering known
        # input parameters from data this pipeline generated at
        # that same metallicity) rather than introducing a
        # deliberate synthetic-data/fit-grid mismatch.
        # load_ck04_grid() requires an exact metallicity match with
        # no interpolation across grid families in any case. Each
        # system's true literature metallicity is recorded
        # separately (unused by this forward-model step) for the
        # record. See scripts/build_joint_benchmarks.py module
        # docstring, scripts/ck04_metallicity_rerun_check.py (empirical
        # confirmation that fitting alpha Cen AB at its
        # closer-to-literature +0.2 grid point makes the fit worse,
        # as expected for this mismatch), and each system's
        # expected_results JSON.
        metallicity=0.0,
        primary_radius=photometric_dict["primary_radius"],
        secondary_radius=photometric_dict["secondary_radius"],
        distance=distance_pc,
        ebv=photometric_dict["ebv"],
    )

    measurements = []

    # synthetic_binary_magnitudes() returns the passband -> magnitude
    # mapping directly (no wrapper key) -- confirmed by reading
    # src/pyseshat/photometry/model.py's `return magnitudes` statement.
    for name, mag in synthetic.items():

        noisy = float(mag) + float(RNG.normal(0, ASSUMED_PHOTOMETRIC_SIGMA_MAG))

        measurements.append({
            "passband": name,
            "magnitude": round(noisy, 4),
            "uncertainty": ASSUMED_PHOTOMETRIC_SIGMA_MAG,
        })

    return measurements, atmosphere_files


